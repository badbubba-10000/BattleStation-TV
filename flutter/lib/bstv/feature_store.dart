// BattleStation TV, 2026. Separate additive feature storage; upstream DB is unchanged.
import 'dart:convert';
import 'dart:isolate';

import 'package:sqlite3/sqlite3.dart';

import 'feature_models.dart';

class FeatureStore {
  FeatureStore(this.path)
    : db = path == ':memory:' ? sqlite3.openInMemory() : sqlite3.open(path) {
    db.execute('PRAGMA busy_timeout=5000');
    if (path != ':memory:') db.execute('PRAGMA journal_mode=WAL');
    final version = db.select('PRAGMA user_version').first.values.first as int;
    if (version > 2) {
      db.close();
      throw const FormatException('Unsupported feature database version');
    }
    transaction(() {
      db.execute('''
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sources (id TEXT PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS guide_channels (source TEXT NOT NULL, id TEXT NOT NULL, name TEXT NOT NULL, PRIMARY KEY(source,id));
CREATE TABLE IF NOT EXISTS programmes (id TEXT PRIMARY KEY, source TEXT NOT NULL, channel TEXT NOT NULL, start INTEGER NOT NULL, end INTEGER NOT NULL, json TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS programmes_window ON programmes(source,channel,start,end);
CREATE INDEX IF NOT EXISTS programmes_time ON programmes(end,start);
CREATE TABLE IF NOT EXISTS mappings (channel_key TEXT PRIMARY KEY, source TEXT NOT NULL, guide_channel TEXT NOT NULL, manual INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, start INTEGER NOT NULL, state TEXT NOT NULL, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS reminders (programme_id TEXT PRIMARY KEY, start INTEGER NOT NULL, json TEXT NOT NULL, delivered INTEGER NOT NULL DEFAULT 0);
''');
      if (!db
          .select('PRAGMA table_info(mappings)')
          .any((row) => row['name'] == 'manual')) {
        db.execute(
          'ALTER TABLE mappings ADD COLUMN manual INTEGER NOT NULL DEFAULT 1',
        );
        // These identity mappings were generated by the old provider fallback.
        // Other existing mappings remain manual and keep their precedence.
        db.execute(
          "UPDATE mappings SET manual=0 WHERE source LIKE 'xtream-%' AND guide_channel=channel_key",
        );
      }
      db.execute('PRAGMA user_version=2');
    });
  }
  final String path;
  final Database db;
  void close() => db.close();
  T transaction<T>(T Function() action) {
    db.execute('BEGIN IMMEDIATE');
    try {
      final value = action();
      db.execute('COMMIT');
      return value;
    } catch (_) {
      db.execute('ROLLBACK');
      rethrow;
    }
  }

  Object? setting(String key) {
    final value = db.select('SELECT value FROM settings WHERE key=?', [
      key,
    ]).firstOrNull?['value'];
    return value is String ? jsonDecode(value) : null;
  }

  void setSetting(String key, Object? value) => db.execute(
    'INSERT OR REPLACE INTO settings VALUES (?,?)',
    [key, jsonEncode(value)],
  );
  List<GuideSource> get sources => [
    for (final row in db.select('SELECT json FROM sources ORDER BY id'))
      GuideSource.fromJson(jsonDecode(row['json'])),
  ];
  void saveSource(GuideSource source) => db.execute(
    'INSERT OR REPLACE INTO sources VALUES (?,?)',
    [source.id, jsonEncode(source.toJson())],
  );
  void removeSource(String id) => transaction(() {
    db.execute('DELETE FROM sources WHERE id=?', [id]);
    db.execute('DELETE FROM programmes WHERE source=?', [id]);
    db.execute('DELETE FROM guide_channels WHERE source=?', [id]);
    db.execute('DELETE FROM mappings WHERE source=?', [id]);
  });
  List<GuideChannel> channels([String? source]) => [
    for (final row in db.select(
      'SELECT * FROM guide_channels WHERE (? IS NULL OR source=?) ORDER BY name',
      [source, source],
    ))
      GuideChannel(sourceId: row['source'], id: row['id'], name: row['name']),
  ];
  void putChannel(GuideChannel channel) => db.execute(
    'INSERT OR REPLACE INTO guide_channels VALUES (?,?,?)',
    [channel.sourceId, channel.id, channel.name],
  );
  void replacePrograms(
    String source,
    List<GuideProgramme> programmes, {
    String? channel,
  }) => transaction(() {
    db.execute(
      'DELETE FROM programmes WHERE source=? AND (? IS NULL OR channel=?)',
      [source, channel, channel],
    );
    final insert = db.prepare(
      'INSERT OR REPLACE INTO programmes VALUES (?,?,?,?,?,?)',
    );
    try {
      for (final p in programmes) {
        insert.execute([
          p.id,
          source,
          p.channelId,
          p.start.millisecondsSinceEpoch,
          p.end.millisecondsSinceEpoch,
          jsonEncode(p.toJson()),
        ]);
      }
    } finally {
      insert.close();
    }
  });
  Future<void> importGuide(String source, ParsedGuide parsed) async {
    if (path != ':memory:') {
      final databasePath = path;
      await Isolate.run(() {
        final worker = FeatureStore(databasePath);
        try {
          worker._import(source, parsed);
        } finally {
          worker.close();
        }
      });
    } else {
      _import(source, parsed);
    }
  }

  void _import(String source, ParsedGuide parsed) => transaction(() {
    db.execute('DELETE FROM programmes WHERE source=?', [source]);
    db.execute('DELETE FROM guide_channels WHERE source=?', [source]);
    for (final c in parsed.channels) {
      putChannel(c);
    }
    final statement = db.prepare(
      'INSERT OR REPLACE INTO programmes VALUES (?,?,?,?,?,?)',
    );
    try {
      for (final p in parsed.programmes) {
        statement.execute([
          p.id,
          source,
          p.channelId,
          p.start.millisecondsSinceEpoch,
          p.end.millisecondsSinceEpoch,
          jsonEncode(p.toJson()),
        ]);
      }
    } finally {
      statement.close();
    }
  });
  List<GuideProgramme> window(
    String source,
    String channel,
    DateTime from,
    DateTime to, {
    String search = '',
  }) =>
      [
            for (final row in db.select(
              "SELECT json FROM programmes WHERE source=? AND channel=? AND end>? AND start<? AND end>start AND length(trim(json_extract(json,'\$.title')))>0 ORDER BY start LIMIT 1000",
              [
                source,
                channel,
                from.toUtc().millisecondsSinceEpoch,
                to.toUtc().millisecondsSinceEpoch,
              ],
            ))
              GuideProgramme.fromJson(jsonDecode(row['json'])),
          ]
          .where(
            (p) =>
                search.isEmpty ||
                '${p.title} ${p.description}'.toLowerCase().contains(
                  search.toLowerCase(),
                ),
          )
          .toList();
  void mapChannel(String key, GuideChannel? channel, {bool manual = true}) {
    if (channel == null) {
      db.execute('DELETE FROM mappings WHERE channel_key=?', [key]);
    } else {
      db.execute('INSERT OR REPLACE INTO mappings VALUES (?,?,?,?)', [
        key,
        channel.sourceId,
        channel.id,
        manual ? 1 : 0,
      ]);
    }
  }

  bool manualMapping(String key) =>
      db.select('SELECT manual FROM mappings WHERE channel_key=?', [
        key,
      ]).firstOrNull?['manual'] ==
      1;
  int programmeCount(String source, [String? channel]) =>
      db.select(
            'SELECT COUNT(*) AS n FROM programmes WHERE source=? AND (? IS NULL OR channel=?)',
            [source, channel, channel],
          ).first['n']
          as int;

  (String, String)? mapping(String key) {
    final row = db.select(
      'SELECT source,guide_channel FROM mappings WHERE channel_key=?',
      [key],
    ).firstOrNull;
    return row == null
        ? null
        : (row['source'] as String, row['guide_channel'] as String);
  }

  void clearMappings() => db.execute('DELETE FROM mappings');
  void clearAutomaticMappings() =>
      db.execute('DELETE FROM mappings WHERE manual=0');
  int channelCount(String source) =>
      db.select('SELECT COUNT(*) AS n FROM guide_channels WHERE source=?', [
            source,
          ]).first['n']
          as int;
  void prune(DateTime before) => db.execute(
    'DELETE FROM programmes WHERE end<?',
    [before.toUtc().millisecondsSinceEpoch],
  );
  List<RecordingJob> get jobs => [
    for (final row in db.select(
      'SELECT json FROM jobs ORDER BY start DESC LIMIT 10000',
    ))
      RecordingJob.fromJson(jsonDecode(row['json'])),
  ];
  void saveJob(RecordingJob job) =>
      db.execute('INSERT OR REPLACE INTO jobs VALUES (?,?,?,?)', [
        job.id,
        job.start.millisecondsSinceEpoch,
        job.state.name,
        jsonEncode(job.toJson()),
      ]);
  void removeJob(String id) => db.execute('DELETE FROM jobs WHERE id=?', [id]);
  void addReminder(GuideProgramme p) => db.execute(
    'INSERT OR REPLACE INTO reminders VALUES (?,?,?,0)',
    [p.id, p.start.millisecondsSinceEpoch, jsonEncode(p.toJson())],
  );
  List<GuideProgramme> dueReminders(DateTime now) {
    final rows = db.select(
      'SELECT * FROM reminders WHERE delivered=0 AND start<=? AND start>?',
      [
        now.toUtc().millisecondsSinceEpoch,
        now.subtract(const Duration(minutes: 5)).toUtc().millisecondsSinceEpoch,
      ],
    );
    final result = [
      for (final row in rows) GuideProgramme.fromJson(jsonDecode(row['json'])),
    ];
    for (final row in rows) {
      db.execute('UPDATE reminders SET delivered=1 WHERE programme_id=?', [
        row['programme_id'],
      ]);
    }
    return result;
  }
}
